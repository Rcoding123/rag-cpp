#!/usr/bin/env python3
"""Bundle the project's documentation (and optionally its source) into one
Markdown file to paste into a language model's context.

  python3 tools/make_context_pack.py                 # docs only
  python3 tools/make_context_pack.py --with-source   # docs + headers, tests, examples, build files
  python3 tools/make_context_pack.py --out FILE

The bundle starts with a file tree and a table of contents, then includes
every file verbatim with a header giving its path and size. Token counts are
estimated at ~4 characters per token.
"""
import argparse
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

DOCS = [
    "llms.txt",
    "docs/ai/README.md",
    "docs/ai/OBJECTIVES.md",
    "docs/ai/PROJECT_MAP.md",
    "docs/ai/SPECS.md",
    "docs/ai/API.md",
    "docs/ai/RAG_ENGINE.md",
    "docs/agent.md",
    "docs/WINDOWS.md",
    "docs/ai/TASK_SPECS.md",
    "docs/ai/LESSONS.md",
    "docs/ai/RESEARCH.md",
    "docs/ai/EXPERIMENTS.md",
    "docs/ai/DECISIONS.md",
    "docs/ai/CONVENTIONS.md",
    "docs/ai/STATUS.md",
    "docs/ai/ORDERFLOW.md",
    "docs/ai/NEXT_SESSION.md",
    "docs/ai/OF16_REAL_ES_PLAN.md",
    "docs/ai/OF17_SIGNAL_CENSUS_PLAN.md",
    "docs/ai/OF18_REGIME_PLAN.md",
    "docs/ai/OF19_FOOTPRINT_PLAN.md",
    "experiments/research_synthesis.md",
    "README.md",
]
SOURCE_GLOBS = [
    "CMakeLists.txt",
    ".github/workflows/ci.yml",
    "include/**/*.hpp",
    "examples/*.cpp",
    "bench/*.cpp",
    "bench/*.hpp",
    "tests/*.cpp",
    "tests/*.hpp",
    "tests/fuzz/*",
    "tools/*.py",
    "python/*.cpp",
    "python/ragrl/**/*.py",
    "python/tests/*.py",
]
FENCE = {".hpp": "cpp", ".cpp": "cpp", ".py": "python", ".yml": "yaml", ".txt": "cmake"}


def tracked_files():
    try:
        out = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
        return sorted(out.split())
    except (OSError, subprocess.CalledProcessError):
        return sorted(str(p.relative_to(ROOT)) for p in ROOT.rglob("*") if p.is_file() and ".git" not in p.parts)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--with-source", action="store_true", help="include headers, tests, examples and build files")
    ap.add_argument("--out", help="output path (default dist/context_pack_{docs,full}.md)")
    args = ap.parse_args()

    files = [f for f in DOCS if (ROOT / f).is_file()]
    if args.with_source:
        seen = set(files)
        for pattern in SOURCE_GLOBS:
            for p in sorted(ROOT.glob(pattern)):
                rel = str(p.relative_to(ROOT))
                if p.is_file() and rel not in seen:
                    files.append(rel)
                    seen.add(rel)

    out = pathlib.Path(args.out).resolve() if args.out else ROOT / "dist" / ("context_pack_full.md" if args.with_source else "context_pack_docs.md")
    out.parent.mkdir(parents=True, exist_ok=True)

    parts = ["# rag-cpp context pack\n",
             "Generated by tools/make_context_pack.py. Contents: "
             + ("documentation and full source" if args.with_source else "documentation") + ".\n",
             "\n## Repository files\n\n```\n" + "\n".join(tracked_files()) + "\n```\n",
             "\n## Contents\n\n" + "\n".join(f"{i + 1}. {f}" for i, f in enumerate(files)) + "\n"]
    total = 0
    for f in files:
        text = (ROOT / f).read_text(encoding="utf-8", errors="replace")
        total += len(text)
        suffix = pathlib.Path(f).suffix
        if suffix == ".md":
            body = text
        else:
            fence = "````" if "```" in text else "```"
            body = f"{fence}{FENCE.get(suffix, '')}\n{text}\n{fence}"
        parts.append(f"\n\n---\n\n## FILE: {f}  ({len(text):,} bytes)\n\n{body}\n")
    out.write_text("".join(parts), encoding="utf-8")
    size = out.stat().st_size
    print(f"wrote {out}: {len(files)} files, {size:,} bytes, ~{size // 4:,} tokens", file=sys.stderr)


if __name__ == "__main__":
    main()
