#!/usr/bin/env python3
"""OF16 phase 2 summary: the 16 sealed OF15 runs scored on real ES (ragrl score-real), one table.

  PYTHONPATH=python python experiments/of16_summary.py --days test --out experiments/of16_real_results.txt
         [--html build-avx512/real/of16_viz/index.html] [--runs build-avx512/rl/runs]

Reads RUN/real/<days>-*/results.json of every sealed of15_* run (for --days test exactly one opening
per run is expected; more is reported as a red flag, and the first is used). Nothing is recomputed
from market data: this is the regenerate step for the committed results file (a test opening is
never repeated). Writes the text table and, with --html, a static page (no external assets).
Decision rule (plan section 4): a headline is an edge claim only if net > 0, t >= t_req (M = 32),
day-clustered 95% CI above 0 and positive in both the Sep and Nov subsets.
"""
import argparse
import html
import json
import math
from pathlib import Path

HEADLINES = ("ensemble", "mean_of_seeds")
BASELINES = ("flat", "delta30", "imbalance_l1")


def n(x, d=2, sign=True):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "-"
    return f"{x:+.{d}f}" if sign else f"{x:.{d}f}"


def load(runs_dir: Path, days: str):
    rows, problems = [], []
    for run in sorted(p for p in runs_dir.glob("of15_*") if (p / "sealed.json").exists()):
        opens = sorted((run / "real").glob(f"{days}-*/results.json")) if (run / "real").exists() else []
        if not opens:
            problems.append(f"{run.name}: no {days} scoring")
            continue
        if days == "test" and len(opens) > 1:
            problems.append(f"{run.name}: {len(opens)} test openings (R10r)")
        r = json.loads((opens[0] if days == "test" else opens[-1]).read_text(encoding="utf-8"))
        sealed = json.loads((run / "sealed.json").read_text(encoding="utf-8"))
        cfg = json.loads((run / "config.json").read_text(encoding="utf-8"))
        rows.append({"run": run.name, "name": cfg.get("name", run.name), "market": cfg["env"].get("market"), "r": r,
                     "sim": sealed.get("summary", {}), "sim_gross": sealed.get("gross", {}), "path": str(opens[0].parent)})
    return rows, problems


def headline_rows(rows, block="base"):
    out = []
    for row in rows:
        b = row["r"]["blocks"].get(block)
        if not b:
            continue
        for h in HEADLINES:
            s = b["summary"].get(h)
            if not s:
                continue
            db = b["day_bootstrap"].get(h, {})
            g = b["gross"].get(h, {})
            subs = {k: v.get("summary", {}).get(h, {}).get("mean") for k, v in b["subsets"].items()}
            dec = b.get("decision", {}).get(h, {})
            pd = b["paired"].get("delta30", {}).get(h, {})
            sim = row["sim"].get(h, {})
            out.append({"name": row["name"], "headline": h, "mean": s["mean"], "se": s["se"], "t": s.get("t"), "orders": s["orders"],
                        "gross": g.get("mean"), "gross_se": g.get("se"), "ci": db.get("ci95") or [None, None], "sep": subs.get("sep"),
                        "nov": subs.get("nov"), "vs_delta30": pd.get("mean"), "vs_delta30_t": pd.get("t"),
                        "sim_mean": sim.get("mean"), "sim_orders": sim.get("orders"), "edge": dec.get("edge_criteria_met")})
    return out


def baseline_rows(rows, block="base"):
    if not rows:
        return []
    b = rows[0]["r"]["blocks"].get(block)
    out = []
    for k in BASELINES:
        s = b["summary"].get(k)
        if not s:
            continue
        db = b["day_bootstrap"].get(k, {})
        g = b["gross"].get(k, {})
        subs = {sk: v.get("summary", {}).get(k, {}).get("mean") for sk, v in b["subsets"].items()}
        out.append({"name": k, "mean": s["mean"], "se": s["se"], "t": s.get("t"), "orders": s["orders"], "gross": g.get("mean"),
                    "gross_se": g.get("se"), "ci": db.get("ci95") or [None, None], "sep": subs.get("sep"), "nov": subs.get("nov")})
    return out


def baselines_agree(rows, block="base"):
    """The baselines see the same tapes and parameters in every run: their results must be identical."""
    ref = None
    for row in rows:
        b = row["r"]["blocks"].get(block, {})
        sig = tuple((k, round(b["summary"][k]["mean"], 9), b["summary"][k]["n"]) for k in BASELINES if k in b.get("summary", {}))
        if ref is None:
            ref = sig
        elif sig != ref:
            return False
    return True


def text_report(rows, problems, days):
    r0 = rows[0]["r"]
    t_req = r0["t_required"]
    L = []
    L.append(f"OF16 phase 2: the 16 sealed OF15 runs on real ES, days = {days}"
             + ("  [dev: not a score]" if days == "dev" else "  (the one test opening per run)"))
    L.append("Generated by experiments/of16_summary.py from RUN/real/" + days + "-*/results.json (ragrl score-real); plan docs/ai/OF16_REAL_ES_PLAN.md.")
    L.append(f"manifest sha256 {r0['manifest_sha256'][:16]}  days {', '.join(sorted(r0['tapes']))}")
    for bname in r0["blocks"]:
        b = r0["blocks"][bname]
        p = b["params"]
        L.append(f"block {bname}: {b['windows']} windows, warm-up {p['warmup_seconds']:g} s, window {p['window_seconds']:g} s, "
                 f"latency {p['latency_buckets']} bucket(s), ${p['fee_dollars']:g}/side; excluded windows {len(b['excluded_windows'])}")
        for e in b["excluded_windows"]:
            L.append(f"    excluded: {json.dumps(e)}")
    L.append(f"Headlines: ensemble and mean of seeds per run, M = {r0['multiplicity']}, t_req = {t_req:.2f}. "
             "Units: net ticks per 600 s window (1 lot). CI = day-clustered bootstrap 95%.")
    for bname in r0["blocks"]:
        L.append("")
        L.append(f"== {bname} ==")
        L.append("baselines" + ("" if baselines_agree(rows, bname) else "  ** NOT IDENTICAL ACROSS RUNS **"))
        L.append(f"  {'policy':<14}{'net':>8}{'se':>7}{'t':>7}{'orders':>8}{'gross':>8}{'day CI95':>20}{'Sep':>8}{'Nov':>8}")
        for x in baseline_rows(rows, bname):
            L.append(f"  {x['name']:<14}{n(x['mean']):>8}{n(x['se'], 2, False):>7}{n(x['t'], 1):>7}{n(x['orders'], 1, False):>8}{n(x['gross']):>8}"
                     f"{'[' + n(x['ci'][0]) + ', ' + n(x['ci'][1]) + ']':>20}{n(x['sep']):>8}{n(x['nov']):>8}")
        L.append(f"  {'run / headline':<30}{'net':>8}{'se':>7}{'t':>7}{'orders':>8}{'gross':>8}{'day CI95':>20}{'Sep':>8}{'Nov':>8}"
                 f"{'vs d30':>8}{'sim net':>9}{'sim ord':>8}  edge")
        for x in headline_rows(rows, bname):
            label = f"{x['name'].replace('of15_', '')} {'ens' if x['headline'] == 'ensemble' else 'mos'}"
            L.append(f"  {label:<30}{n(x['mean']):>8}{n(x['se'], 2, False):>7}{n(x['t'], 1):>7}{n(x['orders'], 1, False):>8}{n(x['gross']):>8}"
                     f"{'[' + n(x['ci'][0]) + ', ' + n(x['ci'][1]) + ']':>20}{n(x['sep']):>8}{n(x['nov']):>8}{n(x['vs_delta30']):>8}"
                     f"{n(x['sim_mean']):>9}{n(x['sim_orders'], 1, False):>8}  {'YES' if x['edge'] else ('-' if x['edge'] is None else 'no')}")
    L.append("")
    met = [f"{x['name']} {x['headline']}" for x in headline_rows(rows, "base") if x["edge"]]
    hard = [(row["name"], f) for row in rows for f in row["r"].get("hard", [])]
    warn = [(row["name"], f) for row in rows for f in row["r"].get("warnings", [])]
    L.append(f"status per run: " + ", ".join(f"{row['name'].replace('of15_', '')} {row['r']['status']}" for row in rows))
    L.append(f"hard red flags: {len(hard)}")
    for name, f in hard:
        L.append(f"  {f['id']} {name} {f.get('block', '')} {f['policy']}: {f['detail']}")
    L.append(f"warnings: {len(warn)}")
    for name, f in warn:
        L.append(f"  {f['id']} {name} {f.get('block', '')} {f['policy']}: {f['detail']}")
    for p in problems:
        L.append(f"problem: {p}")
    if days == "test":
        L.append("")
        L.append("DECISION (plan section 4): " + (f"edge criteria met by {', '.join(met)}: confirm once (phase 2b) before any claim"
                                                 if met else f"no headline meets the edge criteria: NO EDGE ON REAL ES (of {len(headline_rows(rows))} headlines)"))
    return "\n".join(L) + "\n"


def html_report(rows, days, path: Path):
    r0 = rows[0]["r"]
    t_req = r0["t_required"]
    H = headline_rows(rows, "base")
    B = baseline_rows(rows, "base")
    S = {(x["name"], x["headline"]): x for x in headline_rows(rows, "stress")} if "stress" in r0["blocks"] else {}
    items = [("baseline", x) for x in B] + [("headline", x) for x in H]
    # the axis spans the learned headlines and flat / delta30; a baseline far outside (the imbalance rule) is drawn
    # clipped at the edge with its value written next to it
    scale_items = [x for kind, x in items if kind == "headline" or x["name"] != "imbalance_l1"]
    lo = min([v for x in scale_items for v in (x["ci"][0], x["mean"] - 2 * x["se"]) if v is not None] + [-1])
    hi = max([v for x in scale_items for v in (x["ci"][1], x["mean"] + 2 * x["se"]) if v is not None] + [1])
    lo, hi = math.floor(lo), math.ceil(hi)
    W, X0, X1, RH = 980, 330, 960, 22

    def sx(v):
        return X0 + (min(max(v, lo), hi) - lo) / (hi - lo) * (X1 - X0)

    svg = [f'<svg viewBox="0 0 {W} {RH * (len(items) + 2)}" role="img" aria-label="net ticks per window with day-clustered 95% CI">']
    svg.append(f'<line x1="{sx(0):.1f}" x2="{sx(0):.1f}" y1="0" y2="{RH * (len(items) + 1)}" class="zero"/>')
    for i, (kind, x) in enumerate(items):
        y = RH * (i + 1)
        label = x["name"] if kind == "baseline" else f"{x['name'].replace('of15_', '')} · {'ensemble' if x['headline'] == 'ensemble' else 'mean of seeds'}"
        cls = "base" if kind == "baseline" else ("pass" if x.get("edge") else "fail")
        svg.append(f'<text x="{X0 - 8}" y="{y + 4}" text-anchor="end" class="lab">{html.escape(label)}</text>')
        c0, c1 = x["ci"]
        if c0 is not None and c1 is not None:
            svg.append(f'<line x1="{sx(c0):.1f}" x2="{sx(c1):.1f}" y1="{y}" y2="{y}" class="ci {cls}"/>')
        if not lo <= x["mean"] <= hi:
            svg.append(f'<text x="{sx(x["mean"]) + (8 if x["mean"] < lo else -8):.1f}" y="{y + 4}" text-anchor="{"start" if x["mean"] < lo else "end"}" '
                       f'class="tick">off scale: {x["mean"]:+.1f}</text>')
        svg.append(f'<circle cx="{sx(x["mean"]):.1f}" cy="{y}" r="4" class="pt {cls}"><title>{html.escape(label)}: net {x["mean"]:+.2f} '
                   f'(t {n(x["t"], 1)}), {x["orders"]:.1f} orders/window, gross {n(x["gross"])}</title></circle>')
    yb = RH * (len(items) + 1) + 14
    for v in range(lo, hi + 1, max(1, (hi - lo) // 10)):
        svg.append(f'<text x="{sx(v):.1f}" y="{yb}" text-anchor="middle" class="tick">{v}</text>')
    svg.append("</svg>")
    met = [x for x in H if x["edge"]]
    verdict = ("Edge criteria met by " + ", ".join(f"{x['name']} {x['headline']}" for x in met) + ": confirm once before any claim."
               if met else f"No headline meets the edge criteria: no edge on real ES ({len(H)} headlines, t_req {t_req:.2f}).")
    if days == "dev":
        verdict = "Dev rehearsal: not a score."
    trs = []
    for x in H:
        s = S.get((x["name"], x["headline"]), {})
        trs.append(f"<tr><td>{html.escape(x['name'].replace('of15_', ''))}</td><td>{'ensemble' if x['headline'] == 'ensemble' else 'mean of seeds'}</td>"
                   f"<td>{n(x['mean'])}</td><td>{n(x['t'], 1)}</td><td>{n(x['orders'], 1, False)}</td><td>{n(x['gross'])}</td>"
                   f"<td>[{n(x['ci'][0])}, {n(x['ci'][1])}]</td><td>{n(x['sep'])}</td><td>{n(x['nov'])}</td><td>{n(x['sim_mean'])}</td>"
                   f"<td>{n(s.get('mean'))}</td><td>{'YES' if x['edge'] else 'no'}</td></tr>")
    page = f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>OF16 Real ES Scoring</title><style>
:root{{--bg:#fbfaf7;--fg:#1d1d1b;--mut:#6b6a66;--line:#d9d6cf;--pass:#1a7f4b;--fail:#8a8780;--base:#3d5a99}}
@media (prefers-color-scheme:dark){{:root{{--bg:#1b1b1a;--fg:#ecebe7;--mut:#a3a29d;--line:#3a3936;--pass:#4fc387;--fail:#8f8d87;--base:#8aa6e6}}}}
body{{background:var(--bg);color:var(--fg);font:14px/1.45 system-ui,sans-serif;margin:0 auto;max-width:1040px;padding:16px}}
h1{{font-size:20px;margin:0 0 4px}} p{{color:var(--mut);margin:4px 0 12px}} .v{{color:var(--fg);font-weight:600}}
svg{{width:100%;height:auto}} .lab,.tick{{font-size:11px;fill:var(--fg)}} .tick{{fill:var(--mut)}} .zero{{stroke:var(--mut);stroke-dasharray:3 3}}
.ci{{stroke-width:2}} .ci.pass,.pt.pass{{stroke:var(--pass);fill:var(--pass)}} .ci.fail,.pt.fail{{stroke:var(--fail);fill:var(--fail)}}
.ci.base,.pt.base{{stroke:var(--base);fill:var(--base)}}
.tw{{overflow-x:auto}} table{{border-collapse:collapse;font-size:12px;width:100%}} td,th{{border-bottom:1px solid var(--line);padding:3px 6px;text-align:right;white-space:nowrap}}
td:first-child,td:nth-child(2),th:first-child,th:nth-child(2){{text-align:left}}
</style></head><body>
<h1>OF16: OF15 agents on real ES ({html.escape(days)} days)</h1>
<p>{len(rows)} sealed runs, {r0['blocks']['base']['windows']} windows over {len(r0['tapes'])} days, net ticks per 600 s window, 1 lot, $1.50/side, 100 ms latency.
Dots are means, bars the day-clustered 95% CI. Blue: baselines. Edge rule: t ≥ {t_req:.2f}, CI above 0, positive in Sep and Nov.</p>
<p class="v">{html.escape(verdict)}</p>
{''.join(svg)}
<div class="tw"><table><tr><th>run</th><th>headline</th><th>net</th><th>t</th><th>orders</th><th>gross</th><th>day CI95</th><th>Sep</th><th>Nov</th><th>sim net</th><th>stress net</th><th>edge</th></tr>
{''.join(trs)}</table></div>
<p>Generated by experiments/of16_summary.py from ragrl score-real results; plan docs/ai/OF16_REAL_ES_PLAN.md.</p>
</body></html>"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(page, encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--days", choices=("test", "dev"), required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--html")
    ap.add_argument("--runs", default="build-avx512/rl/runs")
    a = ap.parse_args()
    rows, problems = load(Path(a.runs), a.days)
    if not rows:
        raise SystemExit(f"no {a.days} scorings found: " + "; ".join(problems))
    txt = text_report(rows, problems, a.days)
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(txt, encoding="utf-8")
    print(txt)
    if a.html:
        html_report(rows, a.days, Path(a.html))


if __name__ == "__main__":
    main()
